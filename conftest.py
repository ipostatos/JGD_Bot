"""Общая изоляция тестов.

База у приложения одна на всё — лимиты, кэш реестров, профили, новости.
Тесты писали в неё же, и лимиты копились между прогонами: после нескольких
запусков подряд ручка ассистента честно отвечала 429 вместо 400, и падал
тест, который к лимитам отношения не имеет.

Путь подменяется ЗДЕСЬ, а не в фикстуре: модули читают DB_PATH при импорте,
а тестовые модули импортируются раньше, чем выполняется любая фикстура.
"""
import atexit
import os
import shutil
import tempfile
from pathlib import Path

_TMP = tempfile.mkdtemp(prefix="jdg-tests-")
os.environ["JDG_DB"] = str(Path(_TMP) / "test.db")
atexit.register(shutil.rmtree, _TMP, True)
